import * as THREE from 'three';
import { Renderer } from './renderer/Renderer.js';
import { World } from './world/World.js';
import { ChunkStreamer } from './world/ChunkStreamer.js';
import { WorkerPool } from './workers/WorkerPool.js';
import { ChunkRenderer } from './renderer/ChunkRenderer.js';
import { ChunkMaterials } from './renderer/ChunkMaterials.js';
import { BlockTextureArray } from './renderer/textures/BlockTextureArray.js';
import { blockRegistry } from './blocks/index.js';
import { TerrainGenerator } from './terrain/TerrainGenerator.js';
import { SkyRenderer } from './renderer/SkyRenderer.js';
import { CloudRenderer } from './renderer/CloudRenderer.js';
import { WeatherRenderer } from './renderer/WeatherRenderer.js';
import { Atmosphere } from './renderer/Atmosphere.js';
import { DayNightCycle } from './world/DayNightCycle.js';
import { Weather, WeatherType } from './world/Weather.js';

const q = new URLSearchParams(location.search);
const canvas = document.getElementById('game');
canvas.style.cssText = 'position:fixed;inset:0;width:100%;height:100%';
const renderer = new Renderer(canvas);
const seed = Number(q.get('seed') ?? 12345);
const world = new World(seed);
const workerFactory = () => new Worker(new URL('./workers/chunkWorker.js', import.meta.url), { type: 'module' });
const genPool = new WorkerPool(workerFactory, 2);
const meshPool = new WorkerPool(workerFactory, 2);
genPool.broadcast({ type: 'init', seed });
const textures = new BlockTextureArray(blockRegistry);
textures.upload(renderer.webgl);
const materials = new ChunkMaterials(textures.texture);
const rd = Number(q.get('rd') ?? 6);
const chunkRenderer = new ChunkRenderer(world, materials, meshPool, { renderDistance: rd });
renderer.scene.add(chunkRenderer.group);
const streamer = new ChunkStreamer(world, genPool, { renderDistance: rd });
const sky = new SkyRenderer();
renderer.scene.add(sky.group);
const clouds = new CloudRenderer(seed);
renderer.scene.add(clouds.mesh);
const weatherRenderer = new WeatherRenderer(world);
renderer.scene.add(weatherRenderer.mesh);
const atmosphere = new Atmosphere();
const cycle = new DayNightCycle(Number(q.get('time') ?? 3000));
cycle.running = false;
const weather = new Weather();
weather.cycle = false;
if (q.get('weather')) { weather.set(q.get('weather')); weather.rain = 1; weather.thunder = q.get('weather') === WeatherType.THUNDER ? 1 : 0; }
const spawn = new TerrainGenerator(seed).findSpawn();
const cam = renderer.camera;
cam.position.set(spawn.x, spawn.y + Number(q.get('cy') ?? 30), spawn.z);
cam.rotation.set(Number(q.get('pitch') ?? -0.35), Number(q.get('yaw') ?? 0.6), 0);
window.__stats = { chunkRenderer, streamer, world, renderer, materials };
const dir = new THREE.Vector3();
let last = performance.now();
function frame(t) {
  const dt = Math.min(0.1, (t - last) / 1000);
  last = t;
  cycle.update(dt);
  weather.update(dt);
  cam.getWorldDirection(dir);
  atmosphere.update(dt, cycle, weather, { renderDistance: rd, underwater: false, viewDir: dir });
  atmosphere.apply(renderer, materials);
  materials.shared.uTime.value = t / 1000;
  streamer.update(cam.position.x, cam.position.z);
  chunkRenderer.update(cam);
  sky.update(cam, atmosphere.state, t / 1000);
  clouds.update(dt, cam, atmosphere.state, weather.rain);
  weatherRenderer.update(dt, cam.position, weather.rain, cycle.daylight, t / 1000);
  renderer.updateSun(cam.position, atmosphere.state.lightDir);
  renderer.render();
  requestAnimationFrame(frame);
}
requestAnimationFrame(frame);
